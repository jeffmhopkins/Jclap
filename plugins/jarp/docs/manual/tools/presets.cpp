// Prints JArp's factory library as presets.js for the manual: each category with its presets'
// names, blurbs and pattern counts, in library order. Built and run by ../presets.sh.
#include <cstdio>
#include <string>

#include "library.h"

static std::string js(const char *s) {
   std::string o = "\"";
   for (; *s; ++s) {
      if (*s == '"' || *s == '\\')
         o += '\\';
      o += *s;
   }
   return o + "\"";
}

int main() {
   std::printf("// Generated by presets.sh from plugins/jarp/src/library.h. Don't edit by hand.\n");
   std::printf("window.PRESETS = [\n");
   std::string category;
   for (const auto &e : jarp::library::build()) {
      if (e.category != category) {
         if (!category.empty())
            std::printf("  ]],\n");
         category = e.category;
         std::printf("  [%s, [\n", js(e.category).c_str());
      }
      std::printf("    [%s, %s, %d],\n", js(e.name).c_str(), js(e.blurb).c_str(), static_cast<int>(e.patterns.size()));
   }
   std::printf("  ]],\n];\n");
}
